#!/usr/bin/env node
/**
 * THE VOID — build system.
 *
 *   SOURCE   void2-final.html            the canonical app. All shared work lands here.
 *   NATIVE   void-app/assets/void.html   what the Samsung/iOS shell bundles via require()
 *   WEB      copy33thevoid.html          the browser / PWA build
 *
 * The two targets are GENERATED from the source and then PATCHED for their build.
 * They are deliberately NOT byte-identical to the source or to each other — each
 * one carries its own patch set, and that is the point:
 *
 *   NATIVE  2-wide grid, runs inside a WebView that provides the native bridge
 *   WEB     3-wide grid, no shell, browser affordances
 *
 * A feature added to the source reaches BOTH builds on the next `node build.js`.
 * A build-specific difference belongs in PATCHES below and nowhere else — if it is
 * hand-edited into a target it will be overwritten, which is intentional: it keeps
 * the divergence between builds to a list you can read in one screen.
 *
 * Usage:
 *   node build.js          regenerate NATIVE and WEB from SOURCE, apply patches
 *   node build.js --check  verify only; non-zero exit if a target has drifted (CI)
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const SOURCE = path.join(ROOT, 'void2-final.html');
const checkOnly = process.argv.includes('--check');

const read = (p) => fs.readFileSync(p, 'utf8');
const toLF = (s) => s.replace(/\r\n/g, '\n');

/**
 * A patch is [name, find, replace]. `find` must occur EXACTLY ONCE in the source —
 * anything else throws rather than silently patching the wrong line or nothing.
 */
const TARGETS = [
  {
    id: 'native',
    file: 'void-app/assets/void.html',
    label: 'NATIVE  (Samsung + iOS shell)',
    patches: [
      ['build banner',
        '// ── OFFICIAL BUILD: MOBILE · 2-wide grid · Samsung + iOS native shell',
        '// ── OFFICIAL BUILD: NATIVE · 2-wide grid · Samsung + iOS shell (bundled asset)\n' +
        '  // GENERATED by build.js from void2-final.html — do not hand-edit, it is overwritten.'],
      ['build id', "window.VOID_BUILD='mobile';", "window.VOID_BUILD='native';"],
      // The shell supplies window.ReactNativeWebView and the sensing bridge. Code
      // already feature-detects it; this makes the build's intent explicit and gives
      // native-only behaviour somewhere to hang off.
      ['shell flag', 'window.VOID_GRID=2;', 'window.VOID_GRID=2;\n  window.VOID_NATIVE_SHELL=true;'],
      // Grid stays 2-wide: same as source, so there is no grid patch here.
    ],
  },
  {
    id: 'web',
    file: 'copy33thevoid.html',
    label: 'WEB     (browser / PWA)',
    patches: [
      ['build banner',
        '// ── OFFICIAL BUILD: MOBILE · 2-wide grid · Samsung + iOS native shell',
        '// ── OFFICIAL BUILD: WEB · 3-wide grid · browser / PWA\n' +
        '  // GENERATED by build.js from void2-final.html — do not hand-edit, it is overwritten.'],
      ['build id', "window.VOID_BUILD='mobile';", "window.VOID_BUILD='web';"],
      ['grid const', 'window.VOID_GRID=2;', 'window.VOID_GRID=3;\n  window.VOID_NATIVE_SHELL=false;'],
      ['grid class', "document.documentElement.classList.remove('g3');",
        "document.documentElement.classList.add('g3');"],
      ['globe wall columns',
        '.gl-grid{display:grid;grid-template-columns:1fr 1fr;gap:6px}',
        '.gl-grid{display:grid;grid-template-columns:1fr 1fr 1fr;gap:6px}'],
      ['country stream columns',
        '.c-stream-grid{display:grid;grid-template-columns:1fr 1fr;gap:8px;margin-bottom:8px}',
        '.c-stream-grid{display:grid;grid-template-columns:1fr 1fr 1fr;gap:8px;margin-bottom:8px}'],
    ],
  },
];

function buildTarget(srcLF, target) {
  let out = srcLF;
  for (const [name, find, replace] of target.patches) {
    const n = out.split(find).length - 1;
    if (n !== 1) {
      throw new Error(`${target.id}: patch "${name}" matched ${n}x in the source (need exactly 1). ` +
        `The source changed shape — update the patch, do not hand-edit the target.`);
    }
    out = out.replace(find, () => replace);
  }
  return out;
}

let failed = 0;
const ok = (m) => console.log('  ok   ' + m);
const bad = (m) => { console.log('  FAIL ' + m); failed++; };

const srcRaw = read(SOURCE);
const srcLF = toLF(srcRaw);

console.log(checkOnly ? 'CHECK' : 'BUILD');
console.log(`  source: void2-final.html (${srcLF.split('\n').length} lines)\n`);

for (const t of TARGETS) {
  const p = path.join(ROOT, t.file);
  const expected = buildTarget(srcLF, t);
  const actualRaw = fs.existsSync(p) ? read(p) : '';
  const actual = toLF(actualRaw);

  if (actual === expected) {
    ok(`${t.label}  ${t.file}  (${t.patches.length} patches, up to date)`);
    continue;
  }
  if (checkOnly) {
    // Report WHAT drifted, not just that something did.
    const a = actual.split('\n'), e = expected.split('\n');
    let n = 0;
    for (let i = 0; i < Math.max(a.length, e.length); i++) if (a[i] !== e[i]) n++;
    bad(`${t.file} has drifted from source+patches (${n} differing lines) — run: node build.js`);
    continue;
  }
  // Preserve the target's existing newline style so git does not see a whole-file diff.
  const crlf = /\r\n/.test(actualRaw);
  fs.writeFileSync(p, crlf ? expected.replace(/\n/g, '\r\n') : expected);
  ok(`${t.label}  ${t.file}  (${t.patches.length} patches, REGENERATED)`);
}

// ------------------------------------------------------------- deploy output
// Railway serves ONE service: the proxy API and the UI together, same origin.
// The generated builds are copied into void-proxy/public/ so a deploy ships the
// current UI, and so the over-the-air URL (VOID_HTML_URL) has something to point at.
//   /void.html  NATIVE build — what the phone loads at runtime
//   /index.html WEB build    — what a browser gets at the root
// void-proxy lives next to build.js at repo root (NOT parent-of-root).
const PUBLIC = path.join(ROOT, 'void-proxy', 'public');
const DEPLOY = [
  ['native', 'void.html'],
  ['web', 'index.html'],
];
console.log('\nDEPLOY OUTPUT (void-proxy/public)');
if (!fs.existsSync(PUBLIC)) {
  if (checkOnly) bad('void-proxy/public does not exist — run: node build.js');
  else fs.mkdirSync(PUBLIC, { recursive: true });
}
if (fs.existsSync(PUBLIC)) {
  for (const [id, name] of DEPLOY) {
    const t = TARGETS.find((x) => x.id === id);
    const expected = buildTarget(srcLF, t);
    const out = path.join(PUBLIC, name);
    const current = fs.existsSync(out) ? toLF(read(out)) : '';
    if (current === expected) { ok(`${name.padEnd(11)} <- ${id.toUpperCase()} (up to date)`); continue; }
    if (checkOnly) { bad(`public/${name} is stale — run: node build.js`); continue; }
    fs.writeFileSync(out, expected);
    ok(`${name.padEnd(11)} <- ${id.toUpperCase()} (written)`);
  }
}

// ------------------------------------------------------------------- syntax
console.log('\nSYNTAX');
for (const f of [SOURCE, ...TARGETS.map((t) => path.join(ROOT, t.file))]) {
  const h = read(f);
  const re = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi;
  let m, n = 0;
  while ((m = re.exec(h))) { try { new Function(m[1]); } catch (e) { n++; bad(`${path.basename(f)}: ${e.message.slice(0, 70)}`); } }
  if (!n) ok(`${path.relative(ROOT, f)} parses`);
}

// -------------------------------------------------------------- invariants
// Rules that must hold in EVERY build. These are the regressions this codebase
// has actually shipped before, so they are asserted rather than trusted.
console.log('\nINVARIANTS');
const ABSENT = {
  'reels must not chain to the feed sources': 'REEL_FEEDS.concat(BSKY_FEEDS)',
  'combat/NSFW must not be rejected at ingest': 'over_18||!d.id',
  'grid must not be a runtime preference': "localStorage.getItem('v_grid3')",
};
const PRESENT = {
  'no-news filter': 'function isNewsAccount',
  'reel label gate': 'function reelBlocked',
  'reel pet filter': 'REEL_BLOCK_TOPIC',
  'firehose reel lane': 'pullJetstream',
  'persisted dedupe': 'void_seen_ids',
};
for (const t of [{ file: 'void2-final.html' }, ...TARGETS]) {
  const h = toLF(read(path.join(ROOT, t.file)));
  for (const [name, needle] of Object.entries(ABSENT)) if (h.includes(needle)) bad(`${t.file}: ${name}`);
  for (const [name, needle] of Object.entries(PRESENT)) if (!h.includes(needle)) bad(`${t.file}: missing ${name}`);
}
if (!failed) ok(`${Object.keys(ABSENT).length} absences + ${Object.keys(PRESENT).length} features hold in all 3 builds`);

console.log(failed ? `\n${failed} PROBLEM(S)` : '\nOK');
process.exit(failed ? 1 : 0);
