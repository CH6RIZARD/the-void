// Regenerates src/core/data/*.generated.ts from void2-final.html (the source of
// truth) and scripts/*.generated.json. Run: node src/core/__tests__/tools/generate-data.ts
// Values are evaluated from the web source, not re-typed, so they cannot drift.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { webSource } from '../webHarness.ts';

const here = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.resolve(here, '../../data');
const REPO = path.resolve(here, '../../../../..');

function evalDecl(name: string): any {
  const ctx = vm.createContext({});
  vm.runInContext(webSource(name) + `\n;globalThis.__out=${name};`, ctx);
  return JSON.parse(JSON.stringify((ctx as any).__out));
}

// One element per line for arrays/objects of records; compact inside.
function emit(v: any, depth = 0): string {
  const pad = '  '.repeat(depth + 1), end = '  '.repeat(depth);
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    if (v.every(x => x === null || typeof x !== 'object')) return JSON.stringify(v);
    return '[\n' + v.map(x => pad + JSON.stringify(x)).join(',\n') + '\n' + end + ']';
  }
  if (v && typeof v === 'object') {
    const ks = Object.keys(v);
    if (!ks.length) return '{}';
    return '{\n' + ks.map(k => pad + JSON.stringify(k) + ': ' + (depth < 1 ? emit(v[k], depth + 1) : JSON.stringify(v[k]))).join(',\n') + '\n' + end + '}';
  }
  return JSON.stringify(v);
}

const HEADER = '// GENERATED by src/core/__tests__/tools/generate-data.ts from void2-final.html — do not hand-edit.\n';

function write(file: string, body: string) {
  fs.writeFileSync(path.join(DATA, file), HEADER + body);
  console.log('wrote', file, fs.statSync(path.join(DATA, file)).size, 'bytes');
}

