// Bakes the pull-to-refresh camera falls in headless Chrome (the header marks: header/lockups.py).
//   node render.mjs            render into ./out (sheets/*.webp, paths.json)
//   node render.mjs --gpu      same, asking Chrome for the hardware GPU (Linux + NVIDIA: the Vast box)
//   node render.mjs --prebuilt  skip the bundle step and use bake.html (what the Vast box runs)
//   node render.mjs --eyes     just the eyes and brows, flat, straight on (out/eyes.png, for brand marks)
//   node render.mjs --loading  the loading screen's character sheets, straight into the app
//   node render.mjs --install  copy ./out into the app and regenerate src/ui/cameraFallFrames.ts
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, 'out');
const app = path.resolve(here, '../..');
const arg = new Set(process.argv.slice(2));

if (arg.has('--install')) {
  const paths = JSON.parse(fs.readFileSync(path.join(out, 'paths.json'), 'utf8'));
  fs.mkdirSync(path.join(app, 'assets/fall'), { recursive: true });
  for (const p of paths.falls) fs.copyFileSync(path.join(out, 'sheets', p.id + '.webp'), path.join(app, 'assets/fall', p.id + '.webp'));
  const ids = paths.falls.map((p) => p.id);
  const ts = `// Generated by scripts/fall/render.mjs --install. Don't edit by hand; re-bake instead.
// One seamless lap of his falling loop per saved set (Void Loading Lab), sparkles included. Cells of \`cell\` dp
// sit in the sheet in frame order, \`cols\` per row; nl frames at 30 fps. Baked on: ${paths.gpu}
export type CameraFallPath = { name: string; cell: number; cols: number; rows: number; nl: number; sheet: number };
export type CameraFallId = ${ids.map((i) => `'${i}'`).join(' | ')};
export const CAMERA_FALLS: Record<CameraFallId, CameraFallPath> = {
${paths.falls.map((p) => `  ${p.id}: { name: '${p.name}', cell: ${p.cell}, cols: ${p.cols}, rows: ${p.rows}, nl: ${p.nl}, sheet: require('../../assets/fall/${p.id}.webp') },`).join('\n')}
};
`;
  fs.writeFileSync(path.join(app, 'src/ui/cameraFallFrames.ts'), ts);
  console.log('installed', ids.length, 'falls');
  process.exit(0);
}

// --prebuilt: use bake.html as shipped (the Vast box has no app checkout, only this folder).
const bakePath = path.join(here, 'bake.html');
if (!arg.has('--prebuilt')) {
  const { build } = await import('esbuild');
  const bundle = await build({ entryPoints: [path.join(here, 'entry.ts')], bundle: true, write: false, format: 'iife', target: 'chrome120', logLevel: 'warning' });
  fs.writeFileSync(bakePath, `<!doctype html><meta charset="utf-8"><body><script>${bundle.outputFiles[0].text}</script>`);
}
const html = fs.readFileSync(bakePath, 'utf8');

const puppeteer = (await import('puppeteer')).default;
const gpuArgs = arg.has('--gpu')
  ? ['--ignore-gpu-blocklist', '--enable-gpu', '--use-angle=vulkan', '--enable-features=Vulkan', '--disable-vulkan-surface']
  : ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'];
const browser = await puppeteer.launch({
  headless: true,
  executablePath: process.env.CHROME || undefined,
  args: ['--no-sandbox', '--disable-dev-shm-usage', ...gpuArgs],
});
const page = await browser.newPage();
page.on('console', (m) => console.log('[page]', m.text()));
page.on('pageerror', (e) => console.error('[page error]', e.message));
await page.setContent(html, { waitUntil: 'load' });
const gpu = await page.evaluate(() => window.gpuInfo());
console.log('renderer:', gpu);

fs.mkdirSync(path.join(out, 'sheets'), { recursive: true });
const dataOf = (url) => Buffer.from(url.slice(url.indexOf(',') + 1), 'base64');
const t0 = Date.now();
const falls = [];
if (arg.has('--eyes')) {
  fs.writeFileSync(path.join(out, 'eyes.png'), dataOf(await page.evaluate(() => window.bakeEyes())));
  console.log('eyes done'); await browser.close(); process.exit(0);
}
if (arg.has('--loading')) {
  // The loading screen's character, one sheet per saved set, straight into the app (src/features/loading/loadingFrames.ts).
  const sets = [];
  fs.mkdirSync(path.join(app, 'assets/loading'), { recursive: true });
  for (let i = 0; i < await page.evaluate(() => window.LOADING_N); i++) {
    const r = await page.evaluate((k) => window.bakeLoading(k), i);
    fs.writeFileSync(path.join(app, 'assets/loading', r.id + '.webp'), dataOf(r.sheet));
    delete r.sheet; sets.push(r);
    console.log(`loading ${r.id}: ${r.nl} frames`);
  }
  fs.writeFileSync(path.join(app, 'src/features/loading/loadingFrames.ts'), `// Generated by scripts/fall/render.mjs --loading. Don't edit by hand; re-bake instead.
// THE character for the loading screen, one seamless lap per saved set (LOADING_SETS, same order), sparkles included.
// Cells of \`px\` px in frame order, \`cols\` per row, nl frames at \`fps\`. Baked on: ${gpu}
export const LOADING_FRAMES = [
${sets.map((r) => `  { px: ${r.px}, fps: ${r.fps}, cols: ${r.cols}, rows: ${r.rows}, nl: ${r.nl}, sheet: require('../../../assets/loading/${r.id}.webp') },`).join('\n')}
];
`);
  console.log(`done in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  await browser.close(); process.exit(0);
}
for (const id of await page.evaluate(() => window.FALL_IDS)) {
  const r = await page.evaluate((i) => window.bakeFall(i), id);
  fs.writeFileSync(path.join(out, 'sheets', id + '.webp'), dataOf(r.sheet));
  delete r.sheet;
  falls.push(r);
  console.log(`fall ${id} ${r.name}: ${r.nl} frames`);
}
fs.writeFileSync(path.join(out, 'paths.json'), JSON.stringify({ gpu, ms: Date.now() - t0, falls }));
console.log(`done in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
await browser.close();
