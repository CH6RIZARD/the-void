import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
// The night map at 512x256 - the fallback texture's exact shape - so the globe is
// born on the real planet (blurred) instead of the procedural navy ball while the
// full map decodes. Box-filtered 4x4 from the same .bin earthPixels.ts ships.
const ROOT = new URL('../void-app/', import.meta.url);
const SRC = new URL('assets/globe/earth-night.rgba.bin', ROOT);
const DST = new URL('src/features/globe/earthThumb.ts', ROOT);
const W = 2048, H = 1024, F = 4, TW = W / F, TH = H / F;
const src = readFileSync(SRC);
if (src.length !== W * H * 4) { console.log('unexpected size', src.length); process.exit(1); }
const out = new Uint8Array(TW * TH * 4);
for (let ty = 0; ty < TH; ty++) {
  // The .bin rows are south-first; row 0 must be north (textures.ts flipRows).
  const oy = TH - 1 - ty;
  for (let tx = 0; tx < TW; tx++) {
    const acc = [0, 0, 0];
    for (let dy = 0; dy < F; dy++) {
      for (let dx = 0; dx < F; dx++) {
        const i = ((ty * F + dy) * W + tx * F + dx) * 4;
        acc[0] += src[i]; acc[1] += src[i + 1]; acc[2] += src[i + 2];
      }
    }
    const o = (oy * TW + tx) * 4;
    out[o] = Math.round(acc[0] / (F * F));
    out[o + 1] = Math.round(acc[1] / (F * F));
    out[o + 2] = Math.round(acc[2] / (F * F));
    out[o + 3] = 255;
  }
}
const z = deflateSync(out, { level: 9 });
const b64 = z.toString('base64');
console.log('raw', out.length, '-> deflate', z.length, '-> base64', b64.length);
writeFileSync(DST, `// GENERATED by scripts/globe-thumb.mjs - do not edit.
//
// The night map at ${TW}x${TH} RGBA, row 0 = north, deflated + base64'd (${z.length} bytes).
// The globe's first frame draws this while the full map decodes, so the texture
// arriving reads as the planet sharpening rather than a different planet appearing.
export const THUMB_W = ${TW};
export const THUMB_H = ${TH};
export const THUMB_Z = '${b64}';
`);
console.log('wrote earthThumb.ts');
