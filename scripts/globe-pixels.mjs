import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
const SRC = 'D:/void-audit/void-app/assets/globe/earth-night.rgba.bin';
const SW = 2048, SH = 1024, DW = 1024, DH = 512;
const src = readFileSync(SRC);
if (src.length !== SW * SH * 4) { console.log('unexpected size', src.length); process.exit(1); }
// Box-downsample 2x2 -> half. The globe draws at ~640px, so 1024x512 is still
// oversampled, and it quarters what has to ride in the bundle.
const out = Buffer.alloc(DW * DH * 4);
for (let y = 0; y < DH; y++) {
  for (let x = 0; x < DW; x++) {
    const a = ((y * 2) * SW + x * 2) * 4, b = ((y * 2 + 1) * SW + x * 2) * 4;
    const o = (y * DW + x) * 4;
    for (let c = 0; c < 4; c++) {
      out[o + c] = (src[a + c] + src[a + 4 + c] + src[b + c] + src[b + 4 + c]) >> 2;
    }
  }
}
const z = deflateSync(out, { level: 9 });
const b64 = z.toString('base64');
console.log('raw', out.length, '-> deflate', z.length, '-> base64', b64.length);
const body = `// GENERATED by scripts/globe-pixels.mjs - do not edit.
//
// The night map's pixels, deflated and base64'd, carried in the bundle.
//
// Not a file, because the device cannot read one: every build logs
// "[globe] raw map: could not be read" - XHR will not serve the bundled .bin on
// this release build, and the app has no expo-file-system to fall back on.
// Not a PNG, because decoding one in JS costs a 7271 ms block of the thread the
// whole app runs on (the byte-at-a-time unfilter loop over two million bytes).
// Deflate is what is left, and it is the cheap one: fflate's unzlibSync is a
// tight inner loop over ${z.length} bytes, and the picture is mostly black sky,
// which is exactly what deflate is good at - ${(100 - (z.length / out.length) * 100).toFixed(1)}% smaller than the raw pixels.
//
// ${DW}x${DH} RGBA, rows already flipped for DataTexture (which has no flipY),
// downsampled 2:1 from the ${SW}x${SH} source: the globe draws at about 640px,
// so this is still oversampled, and it quarters what rides in the bundle.
export const EARTH_W = ${DW};
export const EARTH_H = ${DH};
export const EARTH_Z = '${b64}';
`;
writeFileSync('D:/void-audit/void-app/src/features/globe/earthPixels.ts', body);
console.log('wrote earthPixels.ts');
