import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
const SRC = 'D:/void-audit/void-app/assets/globe/earth-night.rgba.bin';
const W = 2048, H = 1024;
const out = readFileSync(SRC);
if (out.length !== W * H * 4) { console.log('unexpected size', out.length); process.exit(1); }
// FULL RESOLUTION, no downsample.
//
// This used to halve the map to 1024x512 on the reasoning that "the globe draws
// at ~640px, so 1024x512 is still oversampled". That reasoning is wrong for a
// SPHERE: an equirectangular map wraps 360 degrees, and only ~180 of them face
// the viewer at once. So a 2048-wide source puts ~1024 texture pixels across a
// ~640px globe - sharp - while the halved one put only ~512 across those same
// 640 pixels, which is UNDERSAMPLED. It looked blurred next to the web build,
// and pinch-zoom made it worse. Full res costs 1.4MB deflated; the picture is
// mostly black sky, which is exactly what deflate is good at.
const z = deflateSync(out, { level: 9 });
const b64 = z.toString('base64');
console.log('raw', out.length, '-> deflate', z.length, '-> base64', b64.length);
const body = `// GENERATED by scripts/globe-pixels.mjs - do not edit.
//
// The night map's pixels, deflated and base64'd, carried in the bundle.
//
// Not a file, because the device cannot read one: every build logs
// "[globe] raw map: could not be read" - XHR will not serve the bundled .bin on
// this release build, and the app has no expo-file-system to fall back on.
// Not a PNG, because decoding one in JS costs a 7271 ms block of the thread the
// whole app runs on (the byte-at-a-time unfilter loop over two million bytes).
// Deflate is what is left, and it is the cheap one: fflate's unzlibSync is a
// tight inner loop over ${z.length} bytes, and the picture is mostly black sky,
// which is exactly what deflate is good at - ${(100 - (z.length / out.length) * 100).toFixed(1)}% smaller than the raw pixels.
//
// ${W}x${H} RGBA, rows already flipped for DataTexture (which has no flipY).
// FULL RESOLUTION: an earlier version halved this, which undersampled the
// sphere - only ~180 degrees of the map face the viewer, so 2048 across the
// source is ~1024 across a 640px globe, and halving left ~512. It showed.
export const EARTH_W = ${W};
export const EARTH_H = ${H};
export const EARTH_Z = '${b64}';
`;
writeFileSync('D:/void-audit/void-app/src/features/globe/earthPixels.ts', body);
console.log('wrote earthPixels.ts');
