#!/usr/bin/env python
# The globe's night map at the web's resolution, for the native app.
#
# The web globe loads three-globe's earth-night.jpg at 4096x2048. The app shipped
# a 2048x1024 copy as RGBA, which is why the native globe goes soft when zoomed
# in. A 4096 RGBA map would be 43 MB of GPU memory with mips; ASTC 6x6 carries
# all 13 levels in ~5 MB (PSNR 45.8 dB against the source, vs 38.5 dB for the old
# 2048 map stretched to the same size) and deflates to ~2.3 MB.
#
# Writes void-app/src/features/globe/earthAstc.ts: zlib + base64 of every level's
# blocks back to back, level 0 first, row 0 = north (the jpg's top row).
#
#   pip install pillow
#   python scripts/globe-astc.py <astcenc.exe>   (github.com/ARM-software/astc-encoder releases)
import base64, math, os, subprocess, sys, tempfile, urllib.request, zlib
from PIL import Image

ENC = sys.argv[1]
SRC = 'https://unpkg.com/three-globe/example/img/earth-night.jpg'
OUT = os.path.join(os.path.dirname(__file__), '..', 'void-app', 'src', 'features', 'globe', 'earthAstc.ts')
BX = BY = 6
tmp = tempfile.mkdtemp()
src = os.path.join(tmp, 'src.jpg')
urllib.request.urlretrieve(SRC, src)
img = Image.open(src).convert('RGB')
W, H = img.size
assert (W, H) == (4096, 2048), img.size
blob, w, h, levels = bytearray(), W, H, 0
while True:
    png, astc = os.path.join(tmp, f'l{levels}.png'), os.path.join(tmp, f'l{levels}.astc')
    (img if levels == 0 else img.resize((w, h), Image.LANCZOS)).save(png)
    subprocess.run([ENC, '-cl', png, astc, f'{BX}x{BY}', '-thorough', '-silent'], check=True)
    body = open(astc, 'rb').read()[16:]  # drop the 16-byte .astc header
    assert len(body) == math.ceil(w / BX) * math.ceil(h / BY) * 16
    blob += body
    levels += 1
    if w == 1 and h == 1:
        break
    w, h = max(1, w // 2), max(1, h // 2)
z = base64.b64encode(zlib.compress(bytes(blob), 9)).decode()
with open(OUT, 'w', newline='\n') as f:
    f.write('// GENERATED by scripts/globe-astc.py - do not edit.\n')
    f.write('// The web globe\'s 4096x2048 night map (three-globe earth-night.jpg), ASTC %dx%d,\n' % (BX, BY))
    f.write('// all %d mip levels back to back, level 0 first, row 0 = north; zlib + base64.\n' % levels)
    f.write('export const ASTC_W = %d;\nexport const ASTC_H = %d;\nexport const ASTC_BLOCK = %d;\nexport const ASTC_LEVELS = %d;\nexport const ASTC_BYTES = %d;\n' % (W, H, BX, levels, len(blob)))
    f.write("export const ASTC_Z =\n  '%s';\n" % z)
print('wrote', OUT, levels, 'levels', len(blob), 'bytes,', len(z), 'base64 chars')
