import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { createRequire } from 'node:module';
// The land/water mask the light-theme globe colours by (the night map cannot tell a
// desert from the sea). Source: three-globe's example/img/earth-water.png (water white,
// land black, 1600x800), the same CDN set the web build's night map comes from.
// Out: 1024x512 single-channel, thresholded, row 0 north like earthThumb.ts, 255 = land.
// node scripts/globe-mask.mjs <path/to/earth-water.png>
const { PNG } = createRequire(new URL('../void-app/package.json', import.meta.url))('pngjs');
const png = PNG.sync.read(readFileSync(process.argv[2]));
const W = 1024, H = 512, out = new Uint8Array(W * H);
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
  // box-average the source pixels under this one
  const x0 = Math.floor(x * png.width / W), x1 = Math.floor((x + 1) * png.width / W);
  const y0 = Math.floor(y * png.height / H), y1 = Math.floor((y + 1) * png.height / H);
  let s = 0, n = 0;
  for (let sy = y0; sy < y1; sy++) for (let sx = x0; sx < x1; sx++) { s += png.data[(sy * png.width + sx) * 4]; n++; }
  out[y * W + x] = s / n < 128 ? 255 : 0; // hard coast: the GPU filter softens it, and it deflates 5x smaller
}
const z = deflateSync(out, { level: 9 }).toString('base64');
writeFileSync(new URL('../void-app/src/features/globe/earthMask.ts', import.meta.url),
  `// GENERATED by scripts/globe-mask.mjs - do not edit.\n// Land mask for the light-theme globe: ${W}x${H}, one byte per pixel, row 0 north, 255 = land.\nexport const MASK_W = ${W};\nexport const MASK_H = ${H};\nexport const MASK_Z = '${z}';\n`);
console.log('mask', W + 'x' + H, z.length, 'b64 chars');
