#!/usr/bin/env node
/**
 * resolve-live.js — regenerate the LIVE manifest baked into void2-final.html.
 *
 * WHY THIS EXISTS
 * The app runs from file:// and cannot ask YouTube whether a channel is live —
 * youtube.com sends no CORS headers, so any browser-side liveness check is
 * impossible. Without one, every tile mounts `live_stream?channel=<ID>` and
 * hopes. Measured 2026-08-02: only 4 of 12 channels were actually broadcasting.
 * The other 8 had no videoId to resolve to, so they could ONLY time out, and at
 * 24s each they held every lane while nothing appeared on screen.
 *
 * So liveness is resolved HERE, ahead of time, and the result is baked in. A
 * tile then mounts a direct /embed/<videoId>, which reaches PLAYING in about a
 * second instead of waiting on a server-side channel lookup that may fail.
 *
 * THIS GOES STALE. A live video id changes whenever the broadcaster restarts
 * the stream. Re-run before a build, or on a schedule. `_resolvedAt` is written
 * into the manifest so the app can tell how old it is.
 *
 *   node scripts/resolve-live.js          # report only
 *   node scripts/resolve-live.js --write  # rewrite VOID_LIVE in void2-final.html
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'void2-final.html');
const UA = {
  'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126 Safari/537.36',
  // YouTube answers Error 153 (EMBEDDER_IDENTITY_MISSING_REFERRER) without one.
  'Referer': 'https://thevoid.app/',
  'Accept-Language': 'en-US,en;q=0.9',
};

function extract(name) {
  const html = fs.readFileSync(SRC, 'utf8');
  const i = html.indexOf('const ' + name);
  if (i < 0) return null;
  let depth = 0, j = html.indexOf('[', i), k = j;
  if (j < 0) return null;
  for (; k < html.length; k++) {
    if (html[k] === '[') depth++;
    else if (html[k] === ']') { depth--; if (!depth) break; }
  }
  // eslint-disable-next-line no-eval
  return eval(html.slice(j, k + 1));
}

/** A channel is live only if the page reports isLive AND yields a videoId. */
async function probeChannel(ch) {
  const t0 = Date.now();
  try {
    const r = await fetch('https://www.youtube.com/channel/' + ch.id + '/live', { headers: UA, redirect: 'follow' });
    const t = await r.text();
    const vid = (t.match(/"videoId":"([\w-]{11})"/) || [])[1] || null;
    const isLive = /"isLive":true|"liveBroadcastDetails":\{"isLiveNow":true/.test(t);
    const bad = (/"status":"(ERROR|UNPLAYABLE|LOGIN_REQUIRED)"/.exec(t) || [])[1] || null;
    return { n: ch.n, id: ch.id, vid, live: isLive && !!vid && !bad, bad, ms: Date.now() - t0 };
  } catch (e) {
    return { n: ch.n, id: ch.id, vid: null, live: false, bad: 'FETCH:' + e.message, ms: Date.now() - t0 };
  }
}

async function pool(items, worker, size = 5) {
  const out = [];
  for (let i = 0; i < items.length; i += size) {
    out.push(...await Promise.all(items.slice(i, i + size).map(worker)));
  }
  return out;
}

(async () => {
  const channels = extract('LIVE_CHANNELS') || [];
  if (!channels.length) { console.error('could not extract LIVE_CHANNELS'); process.exit(1); }

  console.log('probing ' + channels.length + ' channels...\n');
  const res = await pool(channels, probeChannel);

  for (const r of res) {
    console.log(
      (r.n || '').padEnd(14),
      (r.live ? 'LIVE  ' : 'dead  '),
      String(r.vid || '-').padEnd(13),
      String(r.ms + 'ms').padEnd(7),
      r.bad || ''
    );
  }

  const live = res.filter(r => r.live).map(r => ({ n: r.n, id: r.id, vid: r.vid }));
  console.log('\nLIVE NOW: ' + live.length + '/' + res.length);

  const manifest = { _resolvedAt: new Date().toISOString(), items: live };

  if (!process.argv.includes('--write')) {
    console.log('\n(report only — pass --write to bake into void2-final.html)');
    console.log(JSON.stringify(manifest, null, 1));
    return;
  }

  let html = fs.readFileSync(SRC, 'utf8');
  const nl = html.includes('\r\n') ? '\r\n' : '\n';
  const block =
    '// GENERATED by scripts/resolve-live.js — do not hand-edit.' + nl +
    '// Only these sources were CONFIRMED broadcasting at _resolvedAt. The app mounts' + nl +
    '// nothing outside this list, because a channel that is not live can only time out.' + nl +
    'const VOID_LIVE=' + JSON.stringify(manifest) + ';';

  if (/const VOID_LIVE=/.test(html)) {
    html = html.replace(/\/\/ GENERATED by scripts\/resolve-live\.js[\s\S]*?const VOID_LIVE=\{[\s\S]*?\};/, block);
  } else {
    html = html.replace('const LIVE_CHANNELS=[', block + nl + 'const LIVE_CHANNELS=[');
  }
  fs.writeFileSync(SRC, html);
  console.log('\nwrote VOID_LIVE into void2-final.html (' + live.length + ' live). Run `node build.js` next.');
})();
